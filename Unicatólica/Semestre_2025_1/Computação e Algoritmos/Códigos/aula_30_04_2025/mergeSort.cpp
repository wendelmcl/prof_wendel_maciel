void intercalar(vector<int>& vetor, int inicio, int meio, int fim) {
    int tamanho1 = meio - inicio + 1;
    int tamanho2 = fim - meio;

    vector<int> esquerda(tamanho1);
    vector<int> direita(tamanho2);

    for (int i = 0; i < tamanho1; i++)
        esquerda[i] = vetor[inicio + i];
    for (int j = 0; j < tamanho2; j++)
        direita[j] = vetor[meio + 1 + j];

    int i = 0, j = 0, k = inicio;

    while (i < tamanho1 && j < tamanho2) {
        if (esquerda[i] <= direita[j]) {
            vetor[k++] = esquerda[i++];
        } else {
            vetor[k++] = direita[j++];
        }
    }

    while (i < tamanho1)
        vetor[k++] = esquerda[i++];
    while (j < tamanho2)
        vetor[k++] = direita[j++];
}

void mergeSort(vector<int>& vetor, int inicio, int fim) {
    if (inicio < fim) {
        int meio = inicio + (fim - inicio) / 2;

        mergeSort(vetor, inicio, meio);
        mergeSort(vetor, meio + 1, fim);

        intercalar(vetor, inicio, meio, fim);
    }
}

void exibirVetor(const vector<int>& vetor) {
    for (int valor : vetor) {
        cout << valor << " ";
    }
    cout << endl;
}

